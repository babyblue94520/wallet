CREATE TABLE IF NOT EXISTS wallet (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  balance BIGINT NOT NULL DEFAULT 0,
  version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS wallet_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at BIGINT NOT NULL DEFAULT 0,
  user_id BIGINT NOT NULL,
  action INT NOT NULL,
  before_balance BIGINT,
  after_balance BIGINT
);

CREATE INDEX IF NOT EXISTS idx_wallet_history_user_id ON wallet_history(user_id);

CREATE TABLE IF NOT EXISTS deposit_record (
  id varchar(36) PRIMARY KEY,
  created_at BIGINT NOT NULL DEFAULT 0,
  channel_id varchar(50) NOT NULL DEFAULT '',
  channel_order_id varchar(100) NOT NULL DEFAULT '',
  status INT NOT NULL DEFAULT 0,
  amount BIGINT NOT NULL DEFAULT 0,
  request_body text
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_deposit_record_channel ON deposit_record(channel_id, channel_order_id);
CREATE INDEX IF NOT EXISTS idx_deposit_record_status_created_at ON deposit_record(status, created_at);

CREATE TABLE IF NOT EXISTS deposit_record2 (
  id varchar(36) PRIMARY KEY,
  created_at BIGINT NOT NULL DEFAULT 0,
  channel_id varchar(50) NOT NULL DEFAULT '',
  channel_order_id varchar(100) NOT NULL DEFAULT '',
  status INT NOT NULL DEFAULT 0,
  amount BIGINT NOT NULL DEFAULT 0,
  request_body text
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_deposit_record2_channel ON deposit_record2(channel_id, channel_order_id);
CREATE INDEX IF NOT EXISTS idx_deposit_record2_status_created_at ON deposit_record2(status, created_at);

CREATE TABLE IF NOT EXISTS deposit_record3 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at BIGINT NOT NULL DEFAULT 0,
  channel_id varchar(50) NOT NULL DEFAULT '',
  channel_order_id varchar(100) NOT NULL DEFAULT '',
  status INT NOT NULL DEFAULT 0,
  amount BIGINT NOT NULL DEFAULT 0,
  request_body text
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_deposit_record3_channel ON deposit_record3(channel_id, channel_order_id);
CREATE INDEX IF NOT EXISTS idx_deposit_record3_status_created_at ON deposit_record3(status, created_at);
